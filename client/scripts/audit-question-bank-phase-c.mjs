#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const questionsPath = path.join(root, 'src/data/questions.json');
const outputArgIndex = process.argv.indexOf('--markdown');
const outputPath = outputArgIndex >= 0 ? process.argv[outputArgIndex + 1] : null;

const raw = JSON.parse(fs.readFileSync(questionsPath, 'utf8'));
const questions = raw.questions ?? raw;

const normalize = (value) => String(value ?? '')
  .toLowerCase()
  .replace(/[^a-z0-9 ]+/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

const textFor = (question) => [
  question.prompt,
  question.leftDesc,
  question.rightDesc,
  ...(question.options ?? []),
].filter(Boolean).join(' ');

const loadedWords = [
  'weird', 'bad', 'wrong', 'flawed', 'lazy', 'scared', 'worry', 'bombed',
  'messy', 'chaos', 'panic', 'hate', 'ignored', 'fail', 'awkward', 'boring',
  'annoying', 'stupid', 'screw', 'crash', 'disaster', 'terrible',
];
const loadedPattern = new RegExp(`\\b(${loadedWords.join('|')})\\b`, 'i');

const youngAdultPattern = /\b(class|campus|internship|school|student|major|club|dorm|first-job|first job|early-career|early adult|young adult|dating|friend|social feed|creator|semester|scholarship|job-search|first-career|portfolio)\b/i;
const adultPattern = /\b(work|workplace|career|family|household|home|management|manager|leadership|promotion|salary|retirement|investment|mortgage|housing|burnout|long-term|direct report|junior colleague|partner|field|role|stakeholders)\b/i;

const byTier = new Map();
for (const question of questions) {
  if (!byTier.has(question.tier)) byTier.set(question.tier, []);
  byTier.get(question.tier).push(question);
}
for (const tierQuestions of byTier.values()) tierQuestions.sort((a, b) => a.id - b.id);

const q19 = byTier.get('19-25') ?? [];
const q25 = byTier.get('25+') ?? [];
const pairedCount = Math.min(q19.length, q25.length);

const exactPromptDuplicates = [];
const exactFullDuplicates = [];
for (let i = 0; i < pairedCount; i += 1) {
  const left = q19[i];
  const right = q25[i];
  if (normalize(left.prompt) === normalize(right.prompt)) {
    exactPromptDuplicates.push(`${left.id}/${right.id}: ${left.prompt}`);
  }
  const leftFull = normalize(`${left.prompt} ${(left.options ?? []).join(' ')}`);
  const rightFull = normalize(`${right.prompt} ${(right.options ?? []).join(' ')}`);
  if (leftFull === rightFull) {
    exactFullDuplicates.push(`${left.id}/${right.id}: ${left.prompt}`);
  }
}

const loadedHits = questions
  .filter((question) => loadedPattern.test(textFor(question)))
  .map((question) => `${question.id} [${question.tier}]: ${question.prompt}`);

const youngAdultThemeHits = q19.filter((question) => youngAdultPattern.test(textFor(question)));
const adultThemeHits = q25.filter((question) => adultPattern.test(textFor(question)));

const percent = (count, total) => (total ? `${((count / total) * 100).toFixed(1)}%` : '0.0%');
const tierCounts = [...byTier.entries()].map(([tier, tierQuestions]) => `- ${tier}: ${tierQuestions.length}`).join('\n');

const pass = exactPromptDuplicates.length === 0
  && exactFullDuplicates.length === 0
  && loadedHits.length === 0
  && youngAdultThemeHits.length / Math.max(q19.length, 1) >= 0.75
  && adultThemeHits.length / Math.max(q25.length, 1) >= 0.75;

const markdown = `# Phase C Question Bank Audit\n\nGenerated by \`scripts/audit-question-bank-phase-c.mjs\`.\n\n## Summary\n\n- Status: ${pass ? 'PASS' : 'FAIL'}\n- Total questions: ${questions.length}\n${tierCounts}\n\n## Duplicate 19–25 / 25+ bank content\n\n- Paired rows audited: ${pairedCount}\n- Exact duplicate prompts: ${exactPromptDuplicates.length}\n- Exact duplicate prompt + options rows: ${exactFullDuplicates.length}\n\n## Valence-loaded wording\n\n- Flagged terms: ${loadedWords.join(', ')}\n- Hits: ${loadedHits.length}\n${loadedHits.length ? `\n### Loaded-word hits\n${loadedHits.slice(0, 50).map((hit) => `- ${hit}`).join('\n')}\n` : ''}\n## Tier-specific scenario coverage\n\n- 19–25 young-adult theme hits: ${youngAdultThemeHits.length} / ${q19.length} (${percent(youngAdultThemeHits.length, q19.length)})\n- 25+ adult theme hits: ${adultThemeHits.length} / ${q25.length} (${percent(adultThemeHits.length, q25.length)})\n\n## Pass rules\n\n- 0 exact duplicate prompts across paired 19–25 / 25+ rows\n- 0 exact duplicate prompt + options rows across paired 19–25 / 25+ rows\n- 0 valence-loaded wording hits from the configured watchlist\n- At least 75% young-adult scenario coverage in 19–25\n- At least 75% adult scenario coverage in 25+\n`;

if (outputPath) {
  fs.mkdirSync(path.dirname(path.join(root, outputPath)), { recursive: true });
  fs.writeFileSync(path.join(root, outputPath), markdown);
}

console.log(markdown);
process.exit(pass ? 0 : 1);
